import Foundation

/// A single stock ledger entry for an item. Current stock is never stored —
/// it is always derived by summing a item's movements in date order (see
/// `StockCalculator`), the same "derive, don't store" approach the sibling
/// Ledger app uses for account balances.
struct StockMovement: Identifiable, Codable, Equatable {
    let id: UUID
    var itemID: UUID
    var variantID: UUID?
    var type: StockMovementType
    /// Signed delta applied to stock: positive increases it, negative
    /// decreases it. For `.stockOut` this is always negative; for
    /// `.correction`/`.opname` it can be either sign depending on whether
    /// the count went up or down.
    var quantity: Int
    var date: Date
    var note: String
    /// Set when this movement was auto-generated by saving a sell
    /// `Transaction`, so the stock card can link back to its source.
    var transactionID: UUID?
    let createdAt: Date

    init(
        id: UUID = UUID(),
        itemID: UUID,
        variantID: UUID? = nil,
        type: StockMovementType,
        quantity: Int,
        date: Date = Date(),
        note: String = "",
        transactionID: UUID? = nil,
        createdAt: Date = Date()
    ) {
        self.id = id
        self.itemID = itemID
        self.variantID = variantID
        self.type = type
        self.quantity = quantity
        self.date = date
        self.note = note
        self.transactionID = transactionID
        self.createdAt = createdAt
    }
}

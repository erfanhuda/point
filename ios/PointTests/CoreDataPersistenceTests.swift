import XCTest
@testable import Point

final class CoreDataPersistenceTests: XCTestCase {
    private var stack: CoreDataStack!

    override func setUp() {
        super.setUp()
        stack = CoreDataStack(inMemory: true)
    }

    func testItemCodeIsAutogeneratedSequentially() throws {
        let repository = CoreDataItemRepository(stack: stack)
        let first = try repository.create(Item(code: "", name: "Coffee", sellPrice: 20000))
        let second = try repository.create(Item(code: "", name: "Tea", sellPrice: 15000))

        XCTAssertEqual(first.code, "ITM-0001")
        XCTAssertEqual(second.code, "ITM-0002")
    }

    func testItemVariantsRoundTripThroughStore() throws {
        let repository = CoreDataItemRepository(stack: stack)
        let variant = ItemVariant(name: "Large", addOnPrice: 5000)
        let saved = try repository.create(Item(code: "", name: "Coffee", sellPrice: 20000, variants: [variant]))

        let fetched = repository.fetchAll().first(where: { $0.id == saved.id })

        XCTAssertEqual(fetched?.variants, [variant])
    }

    func testStockMovementRoundTripsAndFiltersByItem() throws {
        let repository = CoreDataStockMovementRepository(stack: stack)
        let itemID = UUID()
        let otherItemID = UUID()
        try repository.save(StockMovement(itemID: itemID, type: .stockIn, quantity: 10))
        try repository.save(StockMovement(itemID: otherItemID, type: .stockIn, quantity: 5))

        XCTAssertEqual(repository.fetchAll(itemID: itemID).count, 1)
        XCTAssertEqual(repository.fetchAll().count, 2)
    }

    func testTransactionRoundTripsLines() throws {
        let repository = CoreDataTransactionRepository(stack: stack)
        let line = TransactionLine(itemID: UUID(), itemCode: "ITM-0001", itemName: "Coffee", quantity: 2, unitPrice: 20000)
        let transaction = Transaction(lines: [line], discount: 1000, taxEnabled: true, taxRate: 11)
        try repository.save(transaction)

        let fetched = repository.fetchAll().first
        XCTAssertEqual(fetched?.lines, [line])
        XCTAssertEqual(fetched?.discount, 1000)
        XCTAssertEqual(fetched?.taxRate, 11)
    }
}
